const getSheetTemplate = (e) => {
  const zodSchema = e.formFields.map(f => {
    if (f.type === 'number') return "  " + f.name + ": z.coerce.number().optional()";
    return "  " + f.name + ": z.string().optional()";
  }).join(",\n");

  return [
    "'use client'",
    "",
    "import React, { useEffect } from 'react'",
    "import { useForm } from 'react-hook-form'",
    "import { zodResolver } from '@hookform/resolvers/zod'",
    "import { z } from 'zod'",
    "import { useMutation, useQueryClient } from '@tanstack/react-query'",
    "import { toast } from 'sonner'",
    "import { " + e.service + " } from '@/services/" + e.serviceFile + "'",
    "import { X, Loader2 } from 'lucide-react'",
    "",
    "const schema = z.object({",
    zodSchema,
    "})",
    "type FormValues = z.infer<typeof schema>",
    "",
    "interface " + e.singular + "SheetProps {",
    "  open: boolean",
    "  onClose: () => void",
    "  editData?: any | null",
    "}",
    "",
    "export default function " + e.singular + "Sheet({ open, onClose, editData }: " + e.singular + "SheetProps) {",
    "  const qc = useQueryClient()",
    "",
    "  const {",
    "    register,",
    "    handleSubmit,",
    "    reset,",
    "    formState: { errors },",
    "  } = useForm<FormValues>({",
    "    resolver: zodResolver(schema) as any,",
    "    defaultValues: {",
    ...e.formFields.map(f => "      " + f.name + ": " + (f.type === 'number' ? '0' : "''") + ","),
    "    },",
    "  })",
    "",
    "  useEffect(() => {",
    "    if (editData) {",
    "      reset({",
    ...e.formFields.map(f => "        " + f.name + ": editData." + f.name + " ?? " + (f.type === 'number' ? '0' : "''") + ","),
    "      })",
    "    } else {",
    "      reset({",
    ...e.formFields.map(f => "        " + f.name + ": " + (f.type === 'number' ? '0' : "''") + ","),
    "      })",
    "    }",
    "  }, [editData, open, reset])",
    "",
    "  const createMutation = useMutation({",
    "    mutationFn: (data: FormValues) => " + e.service + ".create(data as any),",
    "    onSuccess: () => {",
    "      qc.invalidateQueries({ queryKey: ['" + e.name.toLowerCase() + "'] })",
    "      toast.success('" + e.singular + " created')",
    "      onClose()",
    "    },",
    "    onError: () => toast.error('Failed to create " + e.singular + "'),",
    "  })",
    "",
    "  const updateMutation = useMutation({",
    "    mutationFn: (data: FormValues) => " + e.service + ".update(editData!.id, data as any),",
    "    onSuccess: () => {",
    "      qc.invalidateQueries({ queryKey: ['" + e.name.toLowerCase() + "'] })",
    "      toast.success('" + e.singular + " updated')",
    "      onClose()",
    "    },",
    "    onError: () => toast.error('Failed to update " + e.singular + "'),",
    "  })",
    "",
    "  const onSubmit = (data: FormValues) => {",
    "    if (editData) updateMutation.mutate(data)",
    "    else createMutation.mutate(data)",
    "  }",
    "",
    "  const isPending = createMutation.isPending || updateMutation.isPending",
    "",
    "  if (!open) return null",
    "",
    "  return (",
    "    <div style={{ position: 'fixed', inset: 0, zIndex: 100, display: 'flex', justifyContent: 'flex-end' }}>",
    "      <div onClick={onClose} style={{ position: 'absolute', inset: 0, background: 'rgba(0,0,0,0.22)', backdropFilter: 'blur(2px)' }} />",
    "      <div style={{ position: 'relative', zIndex: 110, width: '100%', maxWidth: 440, height: '100%', background: 'var(--surface)', borderLeft: '1px solid var(--border)', display: 'flex', flexDirection: 'column', boxShadow: 'var(--shadow-xl)' }}>",
    "        <div style={{ padding: '20px 24px', borderBottom: '1px solid var(--border)', display: 'flex', alignItems: 'center', justifyContent: 'space-between' }}>",
    "          <h2 style={{ fontFamily: 'var(--font-display)', fontSize: 18, fontWeight: 500, margin: 0, color: 'var(--foreground)' }}>",
    "            {editData ? 'Edit " + e.singular + "' : 'New " + e.singular + "'}",
    "          </h2>",
    "          <button type=\"button\" onClick={onClose} style={{ background: 'none', border: 'none', cursor: 'pointer', padding: 4, display: 'flex', color: 'var(--foreground-muted)' }}>",
    "            <X size={18} />",
    "          </button>",
    "        </div>",
    "        ",
    "        <form onSubmit={handleSubmit(onSubmit)} style={{ display: 'flex', flexDirection: 'column', flex: 1, overflow: 'hidden' }}>",
    "          <div style={{ flex: 1, overflowY: 'auto', padding: 24, display: 'flex', flexDirection: 'column', gap: 20 }}>",
    ...e.formFields.map(f => [
      "            <div style={{ display: 'flex', flexDirection: 'column', gap: 6 }}>",
      "              <label style={{ fontSize: 13, fontWeight: 500, color: 'var(--foreground)' }}>" + f.label + "</label>",
      "              <input",
      "                {...register('" + f.name + "')}",
      "                style={{ width: '100%', padding: '8px 12px', border: '1px solid var(--border)', borderRadius: 'var(--radius-md)', background: 'var(--surface)', color: 'var(--foreground)', fontSize: 14, outline: 'none', boxSizing: 'border-box' }}",
      "              />",
      "              {errors." + f.name + " && <span style={{ fontSize: 12, color: 'var(--destructive)' }}>{errors." + f.name + ".message as string}</span>}",
      "            </div>"
    ].join('\n')),
    "          </div>",
    "          ",
    "          <div style={{ padding: '16px 24px', borderTop: '1px solid var(--border)', background: 'var(--background)', display: 'flex', gap: 12, justifyContent: 'flex-end' }}>",
    "            <button type=\"button\" onClick={onClose} style={{ padding: '8px 16px', background: 'transparent', border: '1px solid var(--border)', borderRadius: 'var(--radius-md)', fontSize: 13, fontWeight: 500, color: 'var(--foreground)', cursor: 'pointer' }}>Cancel</button>",
    "            <button type=\"submit\" disabled={isPending} style={{ padding: '8px 16px', background: 'var(--accent)', border: 'none', borderRadius: 'var(--radius-md)', fontSize: 13, fontWeight: 500, color: 'white', cursor: 'pointer', display: 'flex', alignItems: 'center', gap: 8, opacity: isPending ? 0.7 : 1 }}>",
    "              {isPending && <Loader2 size={14} className=\"animate-spin\" />}",
    "              {editData ? 'Update' : 'Create'}",
    "            </button>",
    "          </div>",
    "        </form>",
    "      </div>",
    "    </div>",
    "  )",
    "}"
  ].join("\n");
};

entities.forEach(e => {
  const viewDir = path.join('src', 'views', e.name);
  fs.mkdirSync(viewDir, { recursive: true });
  fs.writeFileSync(path.join(viewDir, 'index.tsx'), getIndexTemplate(e));
  fs.writeFileSync(path.join(viewDir, e.singular + 'Sheet.tsx'), getSheetTemplate(e));
  console.log('Created ' + e.name);
});
