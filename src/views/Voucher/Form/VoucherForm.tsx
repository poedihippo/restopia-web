interface DetailRowProps {
  index: number;
  control: Control<VoucherFormValues>;
  onRemove: () => void;
}

const DetailRowBranch = ({ control, index, onRemove }: DetailRowProps) => {
  const { data: branchData, isLoading: isLoadingBranch } =
    useGetBranchList(
      {
        include: "created_by,updated_by,company",
      },
      {
        enabled: true,
      },
    );

  return (
    <div className=" my-4 bg-white shadow-xl rounded-md border-2">
      <div className="flex justify-between items-center px-2 py-2">
        <p>Detail Branch {index + 1}</p>
        <Button type="button" variant="destructive" onClick={onRemove}>
          <Trash />
        </Button>
      </div>
      <div className="flex flex-col gap-4 px-2">
        <div className="flex flex-col gap-2">
          <Label>Branch</Label>
          <Controller
            control={control}
            name={`branches.${index}.branch_id`}
            render={({ field, fieldState }) => (
              <>
                <SearchableSelect
                  isClearable
                  isLoading={isLoadingBranch}
                  placeholder="Select branch..."
                  options={
                    branchData?.data?.map((item) => ({
                      value: item.id,
                      label: `${item?.name}`,
                    })) ?? []
                  }
                  value={
                    branchData?.data
                      ?.filter((item) => item.id === field.value)
                      .map((item) => ({
                        value: item.id,
                        label: `${item?.name}`,
                      }))[0] ?? null
                  }
                  onChange={(selected) => {
                    field.onChange(
                      selected ? (selected as { value: number }).value : null,
                    );
                  }}
                />
                {fieldState.error && (
                  <p className="text-destructive text-sm">
                    {fieldState.error.message}
                  </p>
                )}
              </>
            )}
          />
        </div>
        <div className="flex flex-col gap-2 mb-4">
          <Label>Quota</Label>
          <Controller
            control={control}
            name={`branches.${index}.quota`}
            render={({ field, fieldState }) => (
              <>
                <Input
                  {...field}
                  min={0}
                  onChange={(e) => field.onChange(e.target.valueAsNumber)}
                  type="number"
                  placeholder="0"
                  aria-invalid={!!fieldState.error}
                />
                {fieldState.error && (
                  <p className="text-destructive text-sm">
                    {fieldState.error.message}
                  </p>
                )}
              </>
            )}
          />
        </div>
      </div>
    </div>
  );
};

